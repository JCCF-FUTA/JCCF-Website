// Builds lib/icons.ts from Material Symbols Rounded (weight 400) SVGs.
// Only the icons listed here ship to the browser — never the full icon font (DESIGN.md §9).
// Usage: npm run icons   (after adding a name to ICONS)
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

const require = createRequire(import.meta.url);
const root = path.dirname(require.resolve('@material-symbols/svg-400/package.json'));

const ICONS = [
  'live_tv', 'play_arrow', 'calendar_month', 'schedule', 'location_on', 'groups', 'church',
  'volunteer_activism', 'favorite', 'mail', 'call', 'chat', 'arrow_forward', 'arrow_back', 'north_east',
  'search', 'tune', 'close', 'menu', 'content_copy', 'check', 'check_circle', 'dark_mode', 'light_mode',
  'share', 'menu_book', 'account_balance', 'verified', 'explore', 'event', 'error', 'keyboard_arrow_down',
  'person', 'diversity_3', 'campaign', 'school', 'photo_library', 'article', 'star',
  'water_drop', 'eco', 'circle', 'flare', 'local_library', 'logout', 'download', 'info', 'lock',
  'event_available', 'mic', 'history_edu', 'handshake', 'shield', 'payments', 'receipt_long', 'map',
  'filter_list', 'theater_comedy', 'image', 'login', 'inbox', 'refresh', 'progress_activity', 'open_in_new', 'add',
];

// Filled variants (selected states) only where needed, to keep the client bundle small.
const FILLED = new Set(['check_circle', 'favorite', 'star', 'circle', 'play_arrow']);

const out = {};
for (const name of ICONS) {
  for (const variant of FILLED.has(name) ? [name, `${name}-fill`] : [name]) {
    let svg;
    try { svg = readFileSync(path.join(root, 'rounded', `${variant}.svg`), 'utf8'); } catch { continue; }
    const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
    out[variant.replace(/-/g, '_')] = paths.join(' ');
  }
  if (!out[name]) throw new Error(`Missing icon: ${name}`);
}

const body = `// AUTO-GENERATED by scripts/build-icons.mjs — do not edit by hand.
// Material Symbols Rounded, weight 400 (Apache-2.0). viewBox "0 -960 960 960".
export const icons = ${JSON.stringify(out, null, 2)} as const;
export type IconName = keyof typeof icons;
`;
writeFileSync(new URL('../lib/icons.ts', import.meta.url), body);
console.log(`Wrote ${Object.keys(out).length} icon paths to lib/icons.ts`);
